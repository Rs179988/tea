import { EndpointDefinition, InferredApiSpec } from './types.js';
import { typeToTypeScript } from './schemaInference.js';

function sanitizeIdentifier(name: string): string {
  return name.replace(/[^a-zA-Z0-9]/g, '_');
}

function methodNameToFunction(method: string, routePattern: string): string {
  const parts = routePattern
    .split('/')
    .filter(Boolean)
    .map((p) => {
      if (p.startsWith('{') && p.endsWith('}')) {
        return 'By' + p.slice(1, -1).charAt(0).toUpperCase() + p.slice(2);
      }
      return p.charAt(0).toUpperCase() + p.slice(1);
    });

  const verb = method.toLowerCase();
  return `${verb}${parts.join('')}`;
}

export function generateTypeScriptSdk(spec: InferredApiSpec, clientName = 'ApiClient'): string {
  const interfaces: string[] = [];
  const clientMethods: string[] = [];

  for (let i = 0; i < spec.endpoints.length; i++) {
    const ep = spec.endpoints[i];
    const baseName = methodNameToFunction(ep.method, ep.routePattern);

    // Request Type
    let reqTypeName = 'void';
    if (ep.requestBodySchema && ep.requestBodySchema.kind !== 'null') {
      reqTypeName = `${baseName}Request`;
      interfaces.push(`export type ${reqTypeName} = ${typeToTypeScript(ep.requestBodySchema)};`);
    }

    // Response Type
    const successStatus = ep.responseStatuses.find((s) => s >= 200 && s < 300) || 200;
    const resSchema = ep.responseBodySchemas[successStatus];
    let resTypeName = 'unknown';
    if (resSchema) {
      resTypeName = `${baseName}Response`;
      interfaces.push(`export type ${resTypeName} = ${typeToTypeScript(resSchema)};`);
    }

    // Path Params
    const paramArgs = ep.pathParameters.map((p) => `${p}: string | number`);
    if (reqTypeName !== 'void') {
      paramArgs.push(`data: ${reqTypeName}`);
    }
    paramArgs.push('options?: RequestInit');

    // Method implementation
    const urlFormat = ep.routePattern.replace(/\{(\w+)\}/g, '${$1}');

    clientMethods.push(`
  /**
   * ${ep.method} ${ep.routePattern}
   * Observed ${ep.sampleCount} times in traffic.
   */
  async ${baseName}(${paramArgs.join(', ')}): Promise<${resTypeName}> {
    const path = \`${urlFormat}\`;
    const response = await this.fetch(path, {
      ...options,
      method: '${ep.method}',
      ${
        reqTypeName !== 'void'
          ? `body: JSON.stringify(data),
      headers: {
        'Content-Type': 'application/json',
        ...this.defaultHeaders,
        ...options?.headers,
      },`
          : `headers: {
        ...this.defaultHeaders,
        ...options?.headers,
      },`
      }
    });

    if (!response.ok) {
      throw new Error(\`Request to \${path} failed with status \${response.status}\`);
    }

    return (await response.json()) as ${resTypeName};
  }`);
  }

  return `// ============================================================================
// Auto-generated by TEA (Traffic & Protocol Engineering Anything)
// Clean-Room Strongly Typed SDK
// ============================================================================

${interfaces.join('\n\n')}

export interface ${clientName}Config {
  baseUrl?: string;
  defaultHeaders?: Record<string, string>;
  fetch?: typeof fetch;
}

export class ${clientName} {
  private baseUrl: string;
  private defaultHeaders: Record<string, string>;
  private fetch: typeof fetch;

  constructor(config: ${clientName}Config = {}) {
    this.baseUrl = config.baseUrl || '${spec.baseUrls[0] || 'https://api.example.com'}';
    this.defaultHeaders = config.defaultHeaders || {};
    this.fetch = config.fetch || globalThis.fetch.bind(globalThis);
  }

  private async fetch(endpoint: string, init?: RequestInit): Promise<Response> {
    const url = this.baseUrl.replace(/\\/$/, '') + '/' + endpoint.replace(/^\\//, '');
    return this.fetch(url, init);
  }

  ${clientMethods.join('\n')}
}
`;
}
