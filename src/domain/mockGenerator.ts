import { InferredApiSpec } from './types.js';

export function generateMockServerScript(spec: InferredApiSpec, port = 8080): string {
  const routes: string[] = [];

  for (const ep of spec.endpoints) {
    const successStatus = ep.responseStatuses.find((s) => s >= 200 && s < 300) || 200;
    const example = ep.sampleExamples.find((ex) => ex.statusCode === successStatus);
    const sampleBody = example ? JSON.stringify(example.responseSample, null, 2) : '{"status":"ok"}';

    // Express route format: /users/{id} -> /users/:id
    const expressPath = ep.routePattern.replace(/\{(\w+)\}/g, ':$1');

    routes.push(`
app.${ep.method.toLowerCase()}('${expressPath}', (req, res) => {
  console.log('[TEA Mock] ${ep.method} ${expressPath} accessed');
  res.status(${successStatus}).json(${sampleBody});
});`);
  }

  return `// ============================================================================
// Auto-generated by TEA (Traffic & Protocol Engineering Anything)
// Standalone Stateful Mock Server
// ============================================================================

import http from 'node:http';

const PORT = process.env.PORT || ${port};

const routes = [
${spec.endpoints
  .map((ep) => {
    const successStatus = ep.responseStatuses.find((s) => s >= 200 && s < 300) || 200;
    const example = ep.sampleExamples.find((ex) => ex.statusCode === successStatus);
    const sampleBody = example ? JSON.stringify(example.responseSample) : '{"status":"ok"}';
    const regexPattern = ep.routePattern.replace(/\{(\w+)\}/g, '([^/]+)');
    return `  { method: '${ep.method}', pattern: new RegExp('^${regexPattern}$'), status: ${successStatus}, sample: ${sampleBody} },`;
  })
  .join('\n')}
];

const server = http.createServer((req, res) => {
  const url = new URL(req.url || '/', \`http://\${req.headers.host || 'localhost'}\`);
  const method = req.method?.toUpperCase();

  const matched = routes.find(r => r.method === method && r.pattern.test(url.pathname));

  if (matched) {
    res.writeHead(matched.status, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify(matched.sample, null, 2));
  } else {
    res.writeHead(404, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: 'Endpoint not found in TEA recorded mock', path: url.pathname }));
  }
});

server.listen(PORT, () => {
  console.log(\`[TEA] Stateful Mock Server running on http://localhost:\${PORT}\`);
});
`;
}
